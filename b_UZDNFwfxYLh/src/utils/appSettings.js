export const toDashboardSettings = (account) => {
  if (!account) return defaultAppSettings
  return {
    darkTheme: Boolean(account.dark_theme),
    appLanguage: account.app_language || "en",
    audioLanguage: account.audio_language || "en",
    supportLanguage: account.support_language || "en",
    orderAlertSound: account.order_alert_sound || "classic",
  }
}

export const toApiSettings = (settings) => ({
  dark_theme: Boolean(settings.darkTheme),
  app_language: settings.appLanguage,
  audio_language: settings.audioLanguage,
  support_language: settings.supportLanguage,
  order_alert_sound: settings.orderAlertSound,
})

export const applyAppSettings = (settings = defaultAppSettings) => {
  document.documentElement.classList.toggle("dark", Boolean(settings.darkTheme))
  document.documentElement.lang = settings.appLanguage || "en"
}

