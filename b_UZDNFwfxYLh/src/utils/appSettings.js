export const playOrderAlertSound = (soundValue) => {
  const sound = soundOptions.find((item) => item.value === soundValue) || soundOptions[0]
  if (!sound.frequency) return

  const AudioContext = window.AudioContext || window.webkitAudioContext
  if (!AudioContext) return

  const context = new AudioContext()
  const oscillator = context.createOscillator()
  const gain = context.createGain()
  oscillator.type = sound.value === "urgent" ? "square" : "sine"
  oscillator.frequency.setValueAtTime(sound.frequency, context.currentTime)
  gain.gain.setValueAtTime(0.001, context.currentTime)
  gain.gain.exponentialRampToValueAtTime(0.18, context.currentTime + 0.02)
  gain.gain.exponentialRampToValueAtTime(0.001, context.currentTime + 0.45)
  oscillator.connect(gain)
  gain.connect(context.destination)
  oscillator.start()
  oscillator.stop(context.currentTime + 0.5)
}
